function show($r)
{
    $p = [];
    if ($r['preorder']) {
        $p[] = 'preorder';
    }
    if ($r['pickup']) {
        $p[] = 'pickup=' . $r['pickup']['date'] . ($r['pickup']['after'] ? '>' . $r['pickup']['after'] : '');
    }
    if ($r['courier']) {
        $p[] = 'courier=' . $r['courier']['date'] . ($r['courier']['until'] ? '<' . $r['courier']['until'] : '');
    }
    if ($r['cdek']) {
        $p[] = 'cdek=' . $r['cdek']['from'] . '..' . $r['cdek']['to'];
    }
    return implode(' ', $p) ?: '(ничего)';
}

