#!/usr/bin/env bash
# SessionStart-хук: раз в неделю (в первой сессии начиная с понедельника) напоминает
# проверить товары в витринах главной goodmi.ru и выдать пользователю коды на замену.
# Отметка о том, что на этой неделе напоминание уже было, лежит вне репозитория.

MARKER="$HOME/.claude/goodmi-showcase-check-week"
WEEK="$(date +%G-W%V)"

if [ -f "$MARKER" ] && [ "$(cat "$MARKER" 2>/dev/null)" = "$WEEK" ]; then
  exit 0
fi

printf '%s' "$WEEK" > "$MARKER"

cat <<'JSON'
{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"Еженедельная задача (поставлена пользователем 2026-10-05): это первая сессия на этой неделе. Прежде чем заниматься остальным, проверь товары в витринах главной goodmi.ru (блоки 2681-2687) по памяти project-homepage-showcases: остатки и статус текущих кодов, что закончилось или осталось в 1 штуке, и выдай пользователю коды товаров на замену одной строкой для каждого блока, который нужно обновить. В базу блоков не пиши - коды вносит пользователь. После проверки обнови таблицу кодов в памяти. Если пользователь пришёл со срочным вопросом, сначала коротко сообщи, что проверка витрин запланирована, и сделай её в этой же сессии."},"systemMessage":"Понедельничная проверка товаров на главной GOODMi запланирована на эту сессию."}
JSON
